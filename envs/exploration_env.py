"""
Lightweight Exploration Environment for Autonomous PPO Training
===============================================================

This environment supports two modes:

1) INLINE (standalone) mode:
   - No SmartInfoBus / Orchestrator dependency
   - Computes a lightweight approximation of the 64-dim observation vector

2) PREBAKED (module-observation) mode:
   - Loads the exact 64-dim observation vector produced by your module pipeline
     (generated by scripts/prebake_signals.py)
   - Overrides ONLY the account-dependent slots live each step
   - Training runs much faster because modules are NOT executed during training
   - Integrates training-only rule adapters, prop constraints, and safety filters

Critical invariants:
- Observation layout MUST match training.contracts.obs_contract.OBS_COLUMNS exactly.
- Uses simulation time from prebaked data, NEVER wall-clock time.
- Naive datetimes are treated as Europe/Berlin local time (NOT UTC).
"""

